#include <stdio.h>

// 升序
// 选择排序的意思是：用第1个数字去和后面的每个数字进行比，
            // 然后就把最小的弄到了第一个，开启第二轮
            // 第一轮就确认了第一个就是最小的了，所以从第二个数字开始
            // 也就是拿第二个数字依次去跟后面的比
                            // 这里的“依次去跟后面的”也就是内循环的“i = j + 1”
/*
 * 主函数：实现数组的排序并打印结果
 * 使用选择排序算法对数组进行升序排序
 */
int main(){

    // 定义并初始化一个整型数组
    int arr[]= {3,1,5,4,2};
    // 计算数组长度
    int len = sizeof(arr) / sizeof(int);

    
    for (int j = 0; j < len - 1 ; j++)

    {

        
        // 第一轮：j=0就表示我这一轮是用索引为0的数字去跟后面的依次进行比        i就表示后面为1234索引的数字
        // 第二轮：j=l i=234
        // 第三轮：j=2 i=34
        // 第四轮：j=3 i=4


        // 内层循环：每轮比较并交换元素
         for (int i = j + 1; i < len ; i++)       
        {
            
            // 如果当前元素小于后面元素，则交换它们
            if (arr[i] < arr[j]) 
            {
                // 使用临时变量temp完成两个元素的交换
                int temp = arr[i];
                arr[i] = arr[j] ;
                arr[j] = temp;
            }
            
        }
    }
    

    // 打印排序后的数组元素，用"-"分隔
   for (int i = 0; i < len; i++)
   {
      printf("%d-",arr[i]);
   }
   
    // 程序正常结束，返回0
    return 0;
}