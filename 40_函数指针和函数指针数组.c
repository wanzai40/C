  /*
     * 关键概念：函数指针数组 int (*p[4])(int, int)
     * 
     * 语法分解：
     * 1. p[4]      - p是一个数组，包含4个元素
     * 2. (*p[4])   - 这4个元素都是指针
     * 3. (*p[4])(int, int) - 这些指针指向函数
     * 4. int (*p[4])(int, int) - 指向的函数返回int，接受两个int参数
     * 
     * 为什么这样设计：
     * - 将相关的函数指针组织在一起，形成"函数跳转表"
     * - 可以根据输入索引直接调用对应的函数，避免使用if-else或switch
     * - 这种模式称为"命令模式"或"策略模式"的实现
     */


 /*
     * 调用函数
     * 
     * 表达式分析：(*p[c - 1])(a, b)
     * 
     * 1. c - 1          - 将用户输入(1-4)转换为数组索引(0-3)
     * 2. p[c - 1]       - 取出数组中对应位置的函数指针
     * 3. (*p[c - 1])    - 解引用函数指针，得到函数本身
     * 4. (*p[c - 1])(a, b) - 调用该函数，传入参数a和b
     * 
     * 为什么要用解引用(*)：函数指针可以直接调用，但加*更明确表示这是指针
     * 实际上，p[c-1](a,b) 也可以工作，因为函数名和函数指针可以互换
     */





int jia(int a, int b){
    return a + b;
}

int jian(int a, int b){
    return a - b;
}

int cheng(int a, int b){
    return a * b;
}

int chu(int a, int b){// 注意：这里没有除0检查，实际应用中应该添加
    return a / b;
}


#include <stdio.h>

int main(){

    //定义一个数组去装4个函数指针
      // 数组初始化：将四个函数的地址存入数组
    // 注意：函数名本身就是函数的地址，所以不需要&运算符
    int (*p[4])(int, int) = {jia, jian, cheng, chu};

    //输入三个数字
    int a, b, c;
    printf("请输入2个数字：\n");
    scanf("%d", &a);
    scanf("%d", &b);
    printf("请输入函数编号：\n");
    scanf("%d", &c);

    //调用函数
    int res = (*p[c - 1])(a, b);

    printf("结果为：%d\n", res);




    return 0;
}