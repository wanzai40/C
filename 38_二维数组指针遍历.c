#include <stdio.h>
int main(){

    // 定义一个3行5列的二维数组
    // 在内存中，二维数组是连续存储的：先存第0行，再存第1行，再存第2行
    int arr[3][5] = {
        {1,2,3,4,5},      // 第0行
        {11,22,33,44,55}, // 第1行
        {111,222,333,444,555} // 第2行
    };

    // 二维数组指针遍历
    
    /*
     * 关键概念：数组指针 int (*p)[5]
     * 
     * 为什么这样写：
     * - int (*p)[5] 表示 p 是一个指针，指向一个包含5个int元素的数组
     * - 括号()是必须的，因为 int *p[5] 是指针数组（包含5个指针的数组）
     * - [5] 表示这个指针指向的数组有5个元素
     * 
     * 这种指针的理解：
     * 1. 二维数组 arr 的类型是 int[3][5]
     * 2. arr 作为右值时，会退化成指向第一行的指针
     * 3. 第一行的类型是 int[5]，所以指向第一行的指针类型就是 int(*)[5]
     */
    int (*p)[5] = arr; // p指向二维数组的第一个元素，即第一行

    // 使用指针遍历二维数组
    for(int i = 0; i < 3; i++){        // 外层循环：控制行
        for(int j = 0; j < 5; j++){    // 内层循环：控制列
            /*
             * 表达式分析：*(*p+j)
             * 
             * 1. p 是当前行的指针（指向一整行）
             * 2. *p 解引用p，得到当前行的首地址（即当前行第0列的地址）
             *    - 因为p指向一整行，所以*p相当于这一行的数组名
             *    - 数组名在表达式中会退化成指向第一个元素的指针
             * 3. *p + j 得到当前行第j列的地址（指针算术运算）
             * 4. *(*p+j) 解引用这个地址，得到第i行第j列的值
             * 
             * 
             * 
             * *(*p + j) 的执行过程：
1. p       → 第i行的地址（指向整个行）
2. *p      → 第i行第0列的地址（int*类型）
3. *p + j  → 第i行第j列的地址
4. *(...)  → 取出该地址的值
             * 
             * 为什么这样写：这是通过行指针访问元素的标准方式
             * 等价写法：p[0][j] 或 (*p)[j]
             */
            printf("%d ", *(*p+j)); // p+j表示第i行第j列的元素
        }
        printf("\n");
        
        /*
         * p++ 的含义：
         * - p 是 int(*)[5] 类型的指针
         * - 指针加1，移动 sizeof(int[5]) 个字节
         * - 即跳过一整行（5个int）的大小
         * - 所以 p++ 后，p指向下一行
         * 
         * 为什么需要p++：为了在下一轮外层循环中访问下一行的数据
         */
        p++;    // p++表示指向下一行
    }

    return 0;
}

/*
 * 内存布局示意图：
 * 
 * 地址(低) -> 地址(高)
 * ┌──────┬──────┬──────┬──────┬──────┐
 * │ 1    │ 2    │ 3    │ 4    │ 5    │  ← 第0行 (p初始指向这里)
 * ├──────┼──────┼──────┼──────┼──────┤
 * │ 11   │ 22   │ 33   │ 44   │ 55   │  ← 第1行 (p++后指向这里)
 * ├──────┼──────┼──────┼──────┼──────┤
 * │ 111  │ 222  │ 333  │ 444  │ 555  │  ← 第2行 (p++再指向这里)
 * └──────┴──────┴──────┴──────┴──────┘
 * 
 * p指针的移动：
 * step0: p → 第0行首地址
 * step1: p++ → 跳过5个int → 第1行首地址
 * step2: p++ → 跳过5个int → 第2行首地址
 */

/*
 * 等价写法对比：
 * 
 * 1. 数组下标法（最直观）：
 *    arr[i][j]
 * 
 * 2. 指针偏移法（本题使用）：
 *    *(*p+j)
 * 
 * 3. 其他指针写法：
 *    p[i][j]        // 如果把p当作二维数组名
 *    (*(p+i))[j]    // 先定位到第i行，再取第j个元素
 *    *(p[i] + j)    // p[i]是第i行的首地址
 * 
 * 理解这些等价关系对掌握C语言指针至关重要
 */

/*
 * 如果使用普通指针遍历（另一种方法）：
 * 
 * int *q = &arr[0][0];  // 指向第一个元素
 * for(int i = 0; i < 15; i++){
 *     printf("%d ", *q++);  // 直接遍历所有15个元素
 * }
 * 
 * 这种方式会把二维数组当作一维数组遍历，无法体现行和列的结构
 */