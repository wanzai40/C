#include <stdio.h>
int main(){

    // 定义三个一维数组，每个数组包含3个int元素
    // 这三个数组在内存中可能是连续存储，也可能不连续
    int arr1[3] = {1,2,3};     // 第一个数组
    int arr2[3] = {4,5,6};     // 第二个数组  
    int arr3[3] = {9,10,11};   // 第三个数组

    /*
     * 关键概念：指针数组 int* arr[3]
     * 
     * 把3个数组的内存地址放到一个数组中
     * int* arr[3] 表示：
     * - arr是一个数组，包含3个元素
     * - 每个元素的类型是 int*（指向int的指针）
     * - 这3个指针分别指向arr1、arr2、arr3的首地址
     * 
     * 为什么这样设计：创建一个"数组的数组"，每个元素指向一个独立的一维数组
     * 这比二维数组更灵活，因为每个"行"的长度可以不同
     */
    int* arr[3] = {arr1, arr2, arr3};

    /*
     * 二级指针 int** p
     * 
     * 后一个*是定义指针的固定标记，前一个是arr这个数组中存的是内存地址
     * 
     * int** p 的含义：
     * - p是一个指针变量
     * - 这个指针指向的类型是 int*（指向int的指针）
     * - 所以p可以指向指针数组的首元素
     * 
     * 为什么需要二级指针：
     * - arr是数组名，在表达式中会退化成指向第一个元素的指针
     * - arr的第一个元素类型是 int*，所以指向它的指针类型就是 int**
     * - 二级指针就是"指向指针的指针"
     */
    int** p = arr;  // p指向指针数组的第一个元素（即指向arr1的指针）

    // 使用二级指针遍历"模拟二维数组"
    for(int i = 0; i < 3; i++){        // 外层循环：遍历3个数组（行）
        for(int j = 0; j < 3; j++){    // 内层循环：遍历每个数组的元素（列）
            /*
             * 表达式分析：*(*p+j)
             * 
             * 1. p 是二级指针，当前指向指针数组的第i个元素
             * 2. *p 解引用p，得到当前行的首地址（即arr1、arr2或arr3的首地址）
             *    - *p的类型是 int*，指向一个整型数组的第一个元素
             * 3. *p + j 进行指针算术运算，得到当前行第j个元素的地址
             *    - 因为*p是int*类型，所以+p移动的是sizeof(int)字节
             * 4. *(*p+j) 最终解引用，得到具体的整数值
             * 
             * 这个过程：二级指针 → 一级指针 → 具体元素的值
             */
            printf("%d ", *(*p + j));
        }
        printf("\n");
        
        /*
         * p++ 的含义：
         * - p是int**类型（二级指针）
         * - p++使p移动sizeof(int*)个字节
         * - 即p从指向arr[0]变为指向arr[1]，再到arr[2]
         * - 这样下一轮循环就能访问下一个数组
         */
        p++;  // p指向指针数组的下一个元素
    }

    return 0;
}

/*
 * 内存布局示意图：
 * 
 * 指针数组 arr:         指向的数组:
 * ┌─────────┐         ┌──────────────┐
 * │ arr[0] ─┼────────→│ arr1: 1 2 3 │
 * ├─────────┤         ├──────────────┤
 * │ arr[1] ─┼────────→│ arr2: 4 5 6 │
 * ├─────────┤         ├──────────────┤
 * │ arr[2] ─┼────────→│ arr3: 9 10 11│
 * └─────────┘         └──────────────┘
 * 
 * p指针的移动：
 * 初始：p → arr[0]  →  arr1
 * p++：p → arr[1]  →  arr2  
 * p++：p → arr[2]  →  arr3
 */

/*
 * 这种结构与二维数组的区别：
 * 
 * 1. 内存连续性：
 *    - 二维数组：所有数据在内存中连续存储
 *    - 指针数组：每个数组可能存储在不同的内存区域
 * 
 * 2. 灵活性：
 *    - 二维数组：每行长度必须相同
 *    - 指针数组：每行可以有不同的长度（可以创建"不规则数组"）
 * 
 * 3. 访问效率：
 *    - 二维数组：一次指针运算即可访问 arr[i][j]
 *    - 指针数组：需要两次间接寻址 *(*p+j)
 * 
 * 4. 存储开销：
 *    - 二维数组：只存储数据
 *    - 指针数组：需要额外的空间存储指针
 */

