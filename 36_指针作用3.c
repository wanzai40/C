// 函数的结果和计算状态分开
// 这种设计模式的优点：可以同时返回计算结果和计算状态（是否成功）

#include <stdio.h>

/*
 * 函数：yu (取余函数)
 * 作用：计算两个整数的余数，并通过状态码返回执行结果
 * 参数说明：
 *   num1 - 被除数
 *   num2 - 除数
 *   res - 指向存储余数的变量的指针
 * 
 * 返回值：
 *   0 - 计算成功
 *   -1 - 计算失败（除数为0）
 * 
 * 为什么这样设计：
 *   1. C语言函数只能返回一个值，但我们需要同时返回：
 *      - 计算结果（余数）
 *      - 执行状态（是否成功）
 *   2. 使用指针参数返回计算结果，使用函数返回值返回执行状态
 *   3. 这种设计可以避免除数为0的错误导致程序崩溃
 */
int yu(int num1 , int num2 ,int* res );

int main(){
    // 测试数据
    int a = 10, b = 3;
    int res = 0;  // 用于存储余数，初始化为0

    // 调用取余函数，并获取执行状态
    // 为什么传递&res：函数需要通过指针直接修改res的值
    int flag = yu(a, b, &res);

    // 根据状态码判断计算是否成功
    // flag == 0 表示计算成功
    if (flag == 0)
    {
        printf("%d", res);  // 输出计算结果：10 % 3 = 1
    }
    // 如果flag == -1，表示除数为0，程序不会打印任何内容
    // 这样避免了除0错误导致程序崩溃

    return 0;
}

/*
 * 函数实现：yu
 * 这种设计模式称为"错误码模式"或"状态分离模式"
 * 
 * 执行流程：
 * 1. 首先检查除数是否为0（这是最常见的错误情况）
 * 2. 如果除数为0，直接返回-1，不执行计算
 * 3. 如果除数不为0，进行计算并通过指针返回结果，返回0表示成功
 * 
 * 优点：
 * - 安全性：避免除0错误导致程序崩溃
 * - 清晰性：函数返回值表示状态，指针参数返回结果
 * - 可扩展性：可以添加更多错误码表示不同的错误情况
 */
int yu(int num1 , int num2 ,int* res ){
    // 错误检查：除数不能为0
    // 为什么需要这个检查：
    // 在数学中，除数为0是未定义的
    // 在C语言中，除0会导致程序崩溃（运行时错误）
    if (num2 == 0)
    {
        return -1;  // 返回-1表示计算失败（除数为0）
    }
    
    // 计算余数并通过指针返回
    *res = num1 % num2;  // 修改main函数中的res变量
    
    return 0;  // 返回0表示计算成功
}

/*
 * 程序执行过程：
 * 1. main函数开始执行
 * 2. 定义变量 a=10, b=3, res=0
 * 3. 调用 yu(a, b, &res)
 * 4. 进入yu函数：
 *    - 检查b是否为0？b=3，不是0
 *    - 计算 10 % 3 = 1
 *    - 通过指针 *res = 1，修改main中的res
 *    - 返回0表示成功
 * 5. main中flag接收到返回值0
 * 6. 判断flag==0成立，打印res的值1
 * 
 * 如果除数为0的测试：
 * int a=10, b=0;
 * int flag = yu(a, b, &res);
 * 此时flag = -1，不会打印结果，程序安全运行
 */

/*
 * 扩展：这种模式可以处理多种错误情况
 * 例如，可以扩展为：
 * return -1 // 除数为0
 * return -2 // 溢出错误
 * return -3 // 无效参数
 * 等等...
 */